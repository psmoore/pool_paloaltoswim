#!/usr/bin/env python3
"""
Generate the preview pages.

Each page's own content lives in src/<slug>.html, whose first line is an HTML comment carrying
its <title> and meta description. The chrome around it (the unofficial ribbon, the operator's
masthead, the footer) is the same on every page, so it lives here, configured by SITE below.
Calendars are written as {{cal:<key>}} and filled from EMBEDS. Run `python3 build.py`.
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(HERE, "site.json"), encoding="utf-8"))
EXT = 'target="_blank" rel="noopener noreferrer"'


def cal(m):
    token, label = CFG["embeds"][m.group(1)]
    return (f'<div class="frame"><iframe src="https://www.poolrelay.com/embed/{token}" '
            f'title="{label}" loading="lazy"></iframe></div>')


def shell(slug, title, description, body):
    origin = CFG["origin"][slug]
    site, name = CFG["site"], CFG["name"]
    on = ' class="on" aria-current="page"'
    top = "\n".join(
        f'      <a href="{href}"{on if href == slug else ""}{"" if not href.startswith("http") else " " + EXT}>{label}</a>'
        for label, href in CFG["topbar"])
    nav = "\n".join(
        f'      <a href="{site}{path}" {EXT}><small>{small}</small>{big}</a>' for small, big, path in CFG["nav"])
    return f"""<!doctype html>
<!--
  UNOFFICIAL PREVIEW. Not a {name} website.
  A replica of {origin}
  Generated by build.py from src/{slug} &mdash; edit those, not this file.
-->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow">
<title>{title}</title>
<meta name="description" content="{description}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Source+Sans+3:ital,wght@0,400;0,600;0,700;1,400&display=swap">
<link rel="stylesheet" href="site.css">
</head>
<body>

<div class="preview-note">
  <b>Unofficial preview.</b> Not a {name} page &mdash; a mock-up of
  <a href="{origin}" {EXT}>{origin.replace("https://", "")}</a>
  with its schedule images replaced by a live calendar. Built by
  <a href="https://www.poolrelay.com" {EXT}>Pool Relay</a>.
</div>

<header class="site">
  <a class="logo" href="{CFG["home"]}"><img src="{CFG["logo"]}" alt="{name}"></a>
  <div class="right">
    <nav class="top">
{top}
    </nav>
    <nav class="main">
{nav}
    </nav>
  </div>
</header>

<main>
{body.strip()}
</main>

<footer class="site">
  <b>{name}</b> &nbsp; {CFG["footer"]}
  <p class="fine">This page is an unofficial preview built to demonstrate an embedded
    <a href="https://www.poolrelay.com" {EXT}>Pool Relay</a> calendar. It is not operated by or
    affiliated with {name} or {CFG["city"]}. For official schedules see
    <a href="{origin}" {EXT}>{site.replace("https://", "")}</a>.</p>
</footer>

</body>
</html>
"""


def main():
    for slug in CFG["origin"]:
        src = open(os.path.join(HERE, "src", slug), encoding="utf-8").read()
        m = re.match(r"\s*<!--\s*title:\s*(.*?)\n\s*description:\s*(.*?)\s*-->\s*", src, re.S)
        if not m:
            raise SystemExit(f"src/{slug}: first line must be the title/description comment")
        body = re.sub(r"\{\{cal:(\w+)\}\}", cal, src[m.end():])
        open(os.path.join(HERE, slug), "w", encoding="utf-8").write(shell(slug, m.group(1).strip(), m.group(2).strip(), body))
        print("wrote", slug)


if __name__ == "__main__":
    main()
